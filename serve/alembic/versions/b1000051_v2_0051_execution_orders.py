def upgrade() -> None:
    # 建表顺序满足 FK 依赖：exchange_order_attempts 引用 envelopes + order_state_events；
    # exchange_orders.attempt_id 为普通列（避免 order→attempt→event→order 环形 FK，
    # 否则 alembic autogenerate 无法排序且 downgrade 需 CASCADE）。order 投影由 Logic 维护。
    for name in (
        "execution_authorization_envelopes",
        "exchange_orders",
        "order_state_events",
        "exchange_order_attempts",
    ):
        table = next(t for t in _NEW_TABLES if t.name == name)
        op.execute(table.create_sql)
        for statement in table.index_sql:
            op.execute(statement)
    for name in (
        "exchange_trades",
        "account_reconciliations",
        "workflow_events",
        "external_call_attempts",
        "alert_events",
    ):
        table = next(t for t in _NEW_TABLES if t.name == name)
        op.execute(table.create_sql)
        for statement in table.index_sql:
            op.execute(statement)
    _create_guards()
    _relax_execution_identity_guard()
    _add_lineage()
    _create_outer_lineage_guards()


