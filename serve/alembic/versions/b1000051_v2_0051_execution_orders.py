def _assert_downgrade_safe() -> None:
    allowed = ", ".join(
        f"'{name}'" for name in (*_PRE_0051_RELATIONS, *(t.name for t in _NEW_TABLES))
    )
    owned = ", ".join(f"'{t.name}'" for t in _NEW_TABLES)
    known_indexes = ", ".join(
        f"'{statement.split(' ON ')[0].replace('CREATE INDEX ', '').strip()}'"
        for table in _NEW_TABLES for statement in table.index_sql
    ) or "''"
    known_triggers = ", ".join(
        f"'{name}'" for name in (
            *(f"trg_{t.name}_immutable" for t in _NEW_TABLES if t.append_only),
            "trg_execution_authorization_envelopes_lifecycle",
            "trg_exchange_orders_lifecycle",
            "trg_exchange_order_attempts_lifecycle",
            "trg_account_reconciliations_lifecycle",
            "trg_execution_envelope_permission_check",
            "trg_execution_envelope_intent_bind",
            "trg_exchange_orders_attempt_lineage",
        )
    )
    op.execute(
        f"""
DO $v2_wp05_execution_orders_preflight$
DECLARE unknown_objects text;
        unknown_indexes text;
        unknown_triggers text;
        unresolved_count bigint;
BEGIN
    SELECT (SELECT count(*) FROM trading.exchange_order_attempts
             WHERE result = 'SUBMITTED')
         + (SELECT count(*) FROM trading.exchange_orders
             WHERE status IN ('OPEN','ACK','PARTIAL','UNKNOWN'))
         + (SELECT count(*) FROM trading.account_reconciliations
             WHERE status IN ('RECONCILING','FAILED'))
         + (SELECT count(*) FROM trading.executions
             WHERE quote_checkpoint_id IS NULL)
         + (SELECT count(*) FROM trading.position_lots
             WHERE execution_id IS NULL)
      INTO unresolved_count;
    IF unresolved_count <> 0 THEN
        RAISE EXCEPTION 'v2_wp05_execution_orders_downgrade_unresolved_facts:%', unresolved_count
        USING ERRCODE='55000';
    END IF;
    SELECT string_agg(c.relname, ', ' ORDER BY c.relname)
      INTO unknown_objects
      FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'trading'
       AND c.relkind IN ('r','p','v','m','f')
       AND c.relname NOT IN ({allowed})
       AND NOT EXISTS (
           SELECT 1 FROM pg_inherits i
           JOIN pg_class p ON p.oid = i.inhparent
           JOIN pg_namespace pn ON pn.oid = p.relnamespace
           WHERE i.inhrelid = c.oid AND pn.nspname = 'trading'
             AND ((p.relname = 'outbox_delivery_history'
                   AND c.relname ~ '^outbox_delivery_history_[0-9]{{6}}$')
               OR (p.relname IN ('pm_source_event_batches','pm_source_event_index',
                                  'pm_book_checkpoints','pm_book_levels')
                   AND c.relname ~ ('^' || p.relname || '_[0-9]{{8}}$'))
               OR (p.relname IN ('ai_invocations','ai_tool_calls','ai_validation_results')
                   AND c.relname ~ ('^' || p.relname || '_[0-9]{{6}}$')))
       );
    IF unknown_objects IS NOT NULL THEN
        RAISE EXCEPTION 'v2_wp05_execution_orders_unknown_object:%', unknown_objects
        USING ERRCODE='55000';
    END IF;
    SELECT string_agg(idx.relname, ', ' ORDER BY idx.relname)
      INTO unknown_indexes
      FROM pg_index i
      JOIN pg_class idx ON idx.oid=i.indexrelid
      JOIN pg_class tbl ON tbl.oid=i.indrelid
      JOIN pg_namespace n ON n.oid=tbl.relnamespace
     WHERE n.nspname='trading' AND tbl.relname IN ({owned})
       AND NOT EXISTS (SELECT 1 FROM pg_constraint con WHERE con.conindid=idx.oid)
       AND idx.relname NOT IN ({known_indexes});
    IF unknown_indexes IS NOT NULL THEN
        RAISE EXCEPTION 'v2_wp05_execution_orders_unknown_index:%', unknown_indexes
        USING ERRCODE='55000';
    END IF;
    SELECT string_agg(t.tgname, ', ' ORDER BY t.tgname)
      INTO unknown_triggers
      FROM pg_trigger t
      JOIN pg_class tbl ON tbl.oid=t.tgrelid
      JOIN pg_namespace n ON n.oid=tbl.relnamespace
     WHERE n.nspname='trading' AND tbl.relname IN ({owned})
       AND NOT t.tgisinternal AND t.tgname NOT IN ({known_triggers});
    IF unknown_triggers IS NOT NULL THEN
        RAISE EXCEPTION 'v2_wp05_execution_orders_unknown_trigger:%', unknown_triggers
        USING ERRCODE='55000';
    END IF;
END $v2_wp05_execution_orders_preflight$
"""
    )


