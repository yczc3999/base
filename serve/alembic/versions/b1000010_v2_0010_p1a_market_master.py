def _create_guards() -> None:
    # 0010 专属 guard functions（0002 的 v2_reject_immutable_row 继续复用）
    op.execute(
        """
CREATE FUNCTION trading.v2_guard_universe_frame() RETURNS trigger
LANGUAGE plpgsql AS $v2_guard$
DECLARE
    endpoint_name text;
    endpoint_pages integer;
    roots integer;
    terminals integer;
    bad_links integer;
    reached integer;
    actual_pages integer;
    actual_events integer;
    actual_markets integer;
BEGIN
    IF TG_OP = 'DELETE' OR OLD.status IN ('COMPLETE', 'FAILED') THEN
        RAISE EXCEPTION 'v2_universe_frame_immutable' USING ERRCODE='55000';
    END IF;

    IF NEW.id IS DISTINCT FROM OLD.id
       OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR NEW.started_at IS DISTINCT FROM OLD.started_at THEN
        RAISE EXCEPTION 'v2_universe_frame_identity_immutable' USING ERRCODE='55000';
    END IF;

    IF NEW.status = 'OPEN' THEN
        IF NEW.owner IS DISTINCT FROM OLD.owner
           OR NEW.fencing_token IS DISTINCT FROM OLD.fencing_token THEN
            IF OLD.lease_expires_at > clock_timestamp()
               OR NEW.owner = OLD.owner
               OR NEW.fencing_token <= OLD.fencing_token
               OR NEW.lease_expires_at <= clock_timestamp() THEN
                RAISE EXCEPTION 'v2_universe_frame_lease_cas_failed' USING ERRCODE='55000';
            END IF;
        ELSIF NEW.lease_expires_at < OLD.lease_expires_at THEN
            RAISE EXCEPTION 'v2_universe_frame_lease_regressed' USING ERRCODE='55000';
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.status NOT IN ('COMPLETE', 'FAILED')
       OR NEW.owner IS DISTINCT FROM OLD.owner
       OR NEW.fencing_token IS DISTINCT FROM OLD.fencing_token
       OR NEW.lease_expires_at IS DISTINCT FROM OLD.lease_expires_at
       OR OLD.lease_expires_at <= clock_timestamp() THEN
        RAISE EXCEPTION 'v2_universe_frame_terminal_cas_failed' USING ERRCODE='55000';
    END IF;

    IF NEW.status = 'COMPLETE' THEN
        SELECT count(*),
               coalesce(sum(item_count) FILTER (
                   WHERE endpoint IN ('events_open', 'events_closed')), 0),
               coalesce(sum(item_count) FILTER (
                   WHERE endpoint IN ('markets_open', 'markets_closed')), 0)
          INTO actual_pages, actual_events, actual_markets
          FROM trading.pm_universe_frame_pages
         WHERE frame_id = OLD.id;
        IF NEW.page_count <> actual_pages
           OR NEW.total_events <> actual_events
           OR NEW.total_markets <> actual_markets THEN
            RAISE EXCEPTION 'v2_universe_frame_count_mismatch' USING ERRCODE='55000';
        END IF;

        FOREACH endpoint_name IN ARRAY ARRAY[
            'events_open', 'events_closed', 'markets_open', 'markets_closed'
        ] LOOP
            SELECT count(*),
                   count(*) FILTER (WHERE cursor_input IS NULL),
                   count(*) FILTER (WHERE cursor_output IS NULL)
              INTO endpoint_pages, roots, terminals
              FROM trading.pm_universe_frame_pages
             WHERE frame_id = OLD.id AND endpoint = endpoint_name;
            IF endpoint_pages = 0 OR roots <> 1 OR terminals <> 1 THEN
                RAISE EXCEPTION 'v2_universe_frame_cursor_chain_invalid:%', endpoint_name
                    USING ERRCODE='55000';
            END IF;

            SELECT count(*) INTO bad_links
              FROM trading.pm_universe_frame_pages page
             WHERE page.frame_id = OLD.id
               AND page.endpoint = endpoint_name
               AND (
                    (page.cursor_input IS NOT NULL AND
                     (SELECT count(*) FROM trading.pm_universe_frame_pages predecessor
                       WHERE predecessor.frame_id = OLD.id
                         AND predecessor.endpoint = endpoint_name
                         AND predecessor.cursor_output = page.cursor_input) <> 1)
                    OR
                    (page.cursor_output IS NOT NULL AND
                     (SELECT count(*) FROM trading.pm_universe_frame_pages successor
                       WHERE successor.frame_id = OLD.id
                         AND successor.endpoint = endpoint_name
                         AND successor.cursor_input = page.cursor_output) <> 1)
               );
            IF bad_links <> 0 THEN
                RAISE EXCEPTION 'v2_universe_frame_cursor_chain_invalid:%', endpoint_name
                    USING ERRCODE='55000';
            END IF;

            WITH RECURSIVE chain(id, cursor_output, path) AS (
                SELECT id, cursor_output, ARRAY[id]
                  FROM trading.pm_universe_frame_pages
                 WHERE frame_id = OLD.id AND endpoint = endpoint_name AND cursor_input IS NULL
                UNION ALL
                SELECT page.id, page.cursor_output, chain.path || page.id
                  FROM chain
                  JOIN trading.pm_universe_frame_pages page
                    ON page.frame_id = OLD.id
                   AND page.endpoint = endpoint_name
                   AND page.cursor_input = chain.cursor_output
                 WHERE NOT page.id = ANY(chain.path)
            )
            SELECT count(DISTINCT id) INTO reached FROM chain;
            IF reached <> endpoint_pages THEN
                RAISE EXCEPTION 'v2_universe_frame_cursor_chain_invalid:%', endpoint_name
                    USING ERRCODE='55000';
            END IF;
        END LOOP;
    END IF;
    RETURN NEW;
END $v2_guard$
"""
    )
