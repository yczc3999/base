def _drop_guards() -> None:
    for table in _MARKET_TABLES:
        if table.append_only and table.name != "pm_universe_frame_pages":
            op.execute(
                f"DROP TRIGGER IF EXISTS trg_{table.name}_immutable "
                f"ON {TRADING_SCHEMA}.{table.name}"
            )
    op.execute(
        "DROP TRIGGER IF EXISTS trg_pm_universe_frame_pages_guard "
        "ON trading.pm_universe_frame_pages"
    )
