def _create_guards() -> None:
    """新建 5 张表的 guard：append-only snapshot、reservation 状态机。"""
    for table in _NEW_TABLES:
        if table.append_only:
            op.execute(
                f"CREATE TRIGGER trg_{table.name}_immutable "
                f"BEFORE UPDATE OR DELETE ON {TRADING_SCHEMA}.{table.name} "
                "FOR EACH ROW EXECUTE FUNCTION trading.v2_reject_immutable_row()"
            )
    op.execute(
        r"""
CREATE FUNCTION trading.v2_guard_capital_reservation() RETURNS trigger
LANGUAGE plpgsql AS $v2_guard$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'v2_reservation_immutable' USING ERRCODE='55000';
    END IF;
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'HELD' THEN
            RAISE EXCEPTION 'v2_reservation_initial_state_invalid' USING ERRCODE='23514';
        END IF;
        RETURN NEW;
    END IF;
    IF (to_jsonb(NEW) - 'status' - 'updated_at') IS DISTINCT FROM
       (to_jsonb(OLD) - 'status' - 'updated_at') THEN
        RAISE EXCEPTION 'v2_reservation_payload_immutable' USING ERRCODE='55000';
    END IF;
    IF NOT (
        (OLD.status = 'HELD' AND NEW.status IN ('PROVIDER_BOUND','UNKNOWN','RELEASED'))
        OR (OLD.status = 'UNKNOWN' AND NEW.status IN ('PROVIDER_BOUND','CONSUMED'))
        OR (OLD.status = 'PROVIDER_BOUND' AND NEW.status IN ('CONSUMED','RELEASED'))
    ) THEN
        RAISE EXCEPTION 'v2_reservation_transition_invalid' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $v2_guard$
"""
    )
    op.execute(
        "CREATE TRIGGER trg_capital_reservations_lifecycle "
        "BEFORE INSERT OR UPDATE OR DELETE ON trading.capital_reservations "
        "FOR EACH ROW EXECUTE FUNCTION trading.v2_guard_capital_reservation()"
    )


def _drop_guards() -> None:
    op.execute(
        "DROP TRIGGER IF EXISTS trg_capital_reservations_lifecycle "
        "ON trading.capital_reservations"
    )
    op.execute("DROP FUNCTION IF EXISTS trading.v2_guard_capital_reservation()")
    for table in reversed(_NEW_TABLES):
        if table.append_only:
            op.execute(
                f"DROP TRIGGER IF EXISTS trg_{table.name}_immutable "
                f"ON {TRADING_SCHEMA}.{table.name}"
            )


def upgrade() -> None:
    _assert_vault_backfillable()
    _strengthen_vault()
    _create_vault_version_guards()
    for table in _NEW_TABLES:
        op.execute(table.create_sql)
        for statement in table.index_sql:
            op.execute(statement)
    _create_guards()


def downgrade() -> None:
    _assert_downgrade_safe()
    _drop_guards()
    for table in reversed(_NEW_TABLES):
        op.execute(f"DROP TABLE {TRADING_SCHEMA}.{table.name}")
    _drop_vault_version_guards()
    _unstrengthen_vault()
