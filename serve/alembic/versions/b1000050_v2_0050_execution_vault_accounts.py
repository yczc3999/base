def _assert_vault_backfillable() -> None:
    """非空 vault precondition：任何既有 vault 行都无法无歧义补齐 identity/AAD/version。

    本实现从不解密旧值、从不猜 secret kind；因此任一 vault 表有非空行即 RAISE
    ``VAULT_BACKFILL_DECISION_REQUIRED``（ERRCODE 55000）。env.py 单外层事务保证该
    DO 块抛错时 version 不前进并整体回滚。
    """
    op.execute(
        f"""
DO $v2_wp05_vault_backfill_precondition$
DECLARE vault_hits integer;
BEGIN
    SELECT (
        (SELECT count(*) FROM trading.secret_vault_entries)
        + (SELECT count(*) FROM trading.secret_vault_versions)
        + (SELECT count(*) FROM trading.secret_access_events)
    ) INTO vault_hits;
    IF vault_hits <> 0 THEN
        RAISE EXCEPTION 'VAULT_BACKFILL_DECISION_REQUIRED:'
            'existing vault rows require an explicit identity/AAD/version backfill'
        USING ERRCODE='55000';
    END IF;
END $v2_wp05_vault_backfill_precondition$
"""
    )


