def upgrade() -> None:
    """Create trading schema + 20 foundation tables + current/next-2-month partitions."""
    op.execute(f"CREATE SCHEMA {TRADING_SCHEMA}")

    for table in _trading_tables_in_order():
        op.execute(_create_table_ddl(table))
        _create_table_indexes(table)

    _create_partitions(datetime.now(timezone.utc).date())
    _create_immutability_guards()


def downgrade() -> None:
    """Drop 20 tables (reverse dependency order) + empty trading schema; fail-closed, no CASCADE."""
    for table in reversed(_trading_tables_in_order()):
        op.execute(_drop_table_ddl(table))

    _drop_immutability_guard_functions()

    # fail-closed：20 张表 DROP 后若 schema 仍非空（未知对象），禁止删除 schema 并抛错；
    # 不用 CASCADE。正常路径 schema 为空 → 只删空的 trading schema。
    op.execute(
        "DO $v2_drop_schema$ "
        "DECLARE remaining integer; "
        "BEGIN "
        "  IF EXISTS (SELECT 1 FROM pg_namespace n WHERE n.nspname = 'trading') THEN "
        "    SELECT count(*) INTO remaining FROM pg_class c "
        "      JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='trading'; "
        "    IF remaining = 0 THEN "
        "      EXECUTE 'DROP SCHEMA trading'; "
        "    ELSE "
        "      RAISE EXCEPTION 'v2_trading_schema_not_empty'; "
        "    END IF; "
        "  END IF; "
        "END $v2_drop_schema$"
    )
