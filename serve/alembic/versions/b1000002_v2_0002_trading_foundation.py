def _month_bounds(anchor: date, offset: int):
    """anchor 月 + offset 的 [start, end) 月份边界。"""
    y, m = anchor.year, anchor.month
    total = y * 12 + (m - 1) + offset
    sy, sm = divmod(total, 12)
    start = date(sy, sm + 1, 1)
    ey, em = divmod(total + 1, 12)
    end = date(ey, em + 1, 1)
    return start, end


def _partition_names(anchor: date):
    for offset in (0, 1, 2):
        start, end = _month_bounds(anchor, offset)
        name = f"outbox_delivery_history_{start:%Y%m}"
        yield name, start, end


