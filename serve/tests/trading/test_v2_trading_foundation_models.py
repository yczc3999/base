def test_fk_default_is_restrict_not_cascade():
    """除 lineage junction 与 vault self-supersede 外，FK 默认 RESTRICT（无 ondelete CASCADE）。"""
    for name, t in TRADING.items():
        for fk in t.foreign_keys:
            if name == "artifact_lineage_edges":
                assert fk.ondelete == "CASCADE"
            elif fk.target_fullname.startswith("trading.secret_vault_versions"):
                assert fk.ondelete == "SET NULL"
            else:
                assert fk.ondelete is None, f"{name} FK {fk.name} 应 RESTRICT"


def test_all_check_and_unique_and_index_explicitly_named():
    """除 PK（PG 确定性 <table>_pkey）外，所有 CHECK/UNIQUE/FK/index 必须显式命名。"""
    for name, t in TRADING.items():
        for c in t.constraints:
            if type(c).__name__ == "PrimaryKeyConstraint":
                continue
            assert c.name, f"{name}: 未命名 {type(c).__name__}"
        for fk in t.foreign_keys:
            assert fk.name, f"{name}: 未命名 FK"
        for ix in t.indexes:
            assert ix.name, f"{name}: 未命名 index"


def test_ddl_golden_fragments():
    from sqlalchemy.schema import CreateTable
    # partial index 渲染 WHERE
    tbl = TRADING["transactional_outbox"]
    idx = next(i for i in tbl.indexes if i.name == "ix_transactional_outbox_pending")
    from sqlalchemy.schema import CreateIndex
    sql = str(CreateIndex(idx).compile(dialect=postgresql.dialect()))
    assert "WHERE status = 'PENDING'" in sql
    # 分区表 DDL 渲染 PARTITION BY RANGE
    odh = TRADING["outbox_delivery_history"]
    ddl = str(CreateTable(odh).compile(dialect=postgresql.dialect()))
    assert "PARTITION BY RANGE (completed_at)" in ddl
