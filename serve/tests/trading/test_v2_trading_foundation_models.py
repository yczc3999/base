TRADING = {t.name: t for t in Base.metadata.tables.values() if t.schema == TRADING_SCHEMA}


def _constraints(table, kind):
    return [c for c in TRADING[table].constraints if isinstance(c, kind)]


def _checks(table):
    return [c.name for c in TRADING[table].constraints if isinstance(c, CheckConstraint)]


def _check_sql(table, name):
    return str(next(
        c.sqltext for c in TRADING[table].constraints
        if isinstance(c, CheckConstraint) and c.name == name
    ))


def _uniques(table):
    return [c for c in TRADING[table].constraints if isinstance(c, UniqueConstraint)]


def _fk_targets(table):
    return sorted(fk.target_fullname for fk in TRADING[table].foreign_keys)


