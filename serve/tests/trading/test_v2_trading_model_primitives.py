def _compile_column(typ):
    from sqlalchemy import Column
    return str(CreateColumn("c", Column("c", typ)).compile(dialect=postgresql.dialect()))


def test_bigint_identity_mixin_generated_by_default():
    from sqlalchemy import Column
    from sqlalchemy.orm import DeclarativeBase

    class _B(DeclarativeBase):
        pass

    class T(_B, BigIntIdentityMixin):
        __tablename__ = "t_x"

    col = T.__table__.c.id
    assert col.primary_key
    # Identity(always=False) → GENERATED BY DEFAULT
    assert col.identity is not None
    assert col.identity.always is False
    sql = str(CreateTable(T.__table__).compile(dialect=postgresql.dialect()))
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY" in sql


def test_optimistic_version_mixin_defaults_and_locking():
    from sqlalchemy import create_engine
    from sqlalchemy.orm import DeclarativeBase, Session

    class _B(DeclarativeBase):
        pass

    from sqlalchemy import BigInteger, String
    from sqlalchemy.orm import mapped_column

    class T(_B, OptimisticVersionMixin):
        __tablename__ = "t_v"
        id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
        name: Mapped[str] = mapped_column(String)

    ver = T.__table__.c.version
    assert ver.default.arg == 1
    assert ver.server_default.arg == "1" or getattr(ver.server_default, "text", "1") is not None
    # SQLAlchemy optimistic locking 必须绑定 mapped Column；字符串会在 flush 时抛 ArgumentError。
    assert T.__mapper__.version_id_col is ver

    engine = create_engine("sqlite://")
    _B.metadata.create_all(engine)
    with Session(engine, expire_on_commit=False) as session:
        row = T(id=1, name="before")
        session.add(row)
        session.commit()
        assert row.version == 1
        row.name = "after"
        session.commit()
        assert row.version == 2


def test_timestamp_mixin_has_both_columns():
    from sqlalchemy.orm import DeclarativeBase

    class _B(DeclarativeBase):
        pass

    from sqlalchemy import BigInteger
    from sqlalchemy.orm import mapped_column

    class T(_B, TimestampMixin):
        __tablename__ = "t_ts"
        id: Mapped[int] = mapped_column(BigInteger, primary_key=True)

    assert "created_at" in T.__table__.c
    assert "updated_at" in T.__table__.c
    assert T.__table__.c.created_at.server_default is not None
    assert T.__table__.c.updated_at.server_default is not None


def test_created_at_mixin_only():
    from sqlalchemy.orm import DeclarativeBase

    class _B(DeclarativeBase):
        pass

    from sqlalchemy import BigInteger
    from sqlalchemy.orm import mapped_column

    class T(_B, CreatedAtMixin):
        __tablename__ = "t_ca"
        id: Mapped[int] = mapped_column(BigInteger, primary_key=True)

    assert "created_at" in T.__table__.c
    assert "updated_at" not in T.__table__.c
