from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateTable, CreateColumn

from sqlalchemy.orm import Mapped

from app.models.trading.constants import TRADING_SCHEMA
from app.models.trading.mixins import (
    BigIntIdentityMixin,
    CreatedAtMixin,
    OptimisticVersionMixin,
    TimestampMixin,
)
from app.models.trading.types import (
    base_unit_type,
    external_id_type,
    sha256_type,
    utc_timestamp_type,
)


def test_trading_schema_constant():
    assert TRADING_SCHEMA == "trading"


def test_type_factories_return_independent_instances():
    a, b = utc_timestamp_type(), utc_timestamp_type()
    assert a is not b
    assert base_unit_type() is not base_unit_type()
    assert sha256_type() is not sha256_type()
    assert external_id_type() is not external_id_type()


def test_utc_timestamp_type():
    t = utc_timestamp_type()
    assert isinstance(t, DateTime)
    assert t.timezone is True
    sql = str(t.compile(dialect=postgresql.dialect()))
    assert "TIMESTAMP WITH TIME ZONE" in sql


def test_base_unit_type():
    t = base_unit_type()
    assert isinstance(t, Numeric)
    assert t.precision == 38
    assert t.scale == 0
    sql = str(t.compile(dialect=postgresql.dialect()))
    assert "NUMERIC(38, 0)" in sql


