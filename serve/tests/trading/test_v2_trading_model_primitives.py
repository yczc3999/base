"""
WP-01A-02 ORM kernel —— type factory / mixin 定向验收。

type factory 每次调用返回**独立**实例；DDL 分别为 ``TIMESTAMPTZ``、``NUMERIC(38,0)``、
``VARCHAR(64) COLLATE "C"``、``TEXT COLLATE "C"``。mixin：identity 为 ``GENERATED BY
DEFAULT``，version Python/server 初值 1 且启用 SQLAlchemy optimistic locking。
"""

