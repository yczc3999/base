def _seed_payout_env(url):
    """插入 market + token + 2 token versions + artifact + snapshot 供 payout 测试。

    PASS spec 必须与完整 payout set 在同一事务提交；这里只预留 spec id 并返回
    对应 INSERT statement，避免用一个暂时不完整的已提交 spec 污染 fixture。
    """
    now = datetime.now(timezone.utc)
    _execute(url, "INSERT INTO trading.pm_markets (gamma_market_id, condition_id, active) VALUES ('m1', 'c1', true)")
    mid = _query(url, "SELECT id FROM trading.pm_markets WHERE gamma_market_id='m1'")[0][0]
    _execute(url, "INSERT INTO trading.pm_tokens (token_id, market_id, outcome_index) VALUES ('t0', :m, 0), ('t1', :m, 1)", {"m": mid})
    t0 = _query(url, "SELECT id FROM trading.pm_tokens WHERE token_id='t0'")[0][0]
    t1 = _query(url, "SELECT id FROM trading.pm_tokens WHERE token_id='t1'")[0][0]
    _execute(url, "INSERT INTO trading.pm_market_versions (market_id, version_no, observed_at, received_at, normalized_hash) VALUES (:m, 1, now(), now(), :h)", {"m": mid, "h": "a" * 64})
    mv = _query(url, "SELECT id FROM trading.pm_market_versions WHERE market_id=:m", {"m": mid})[0][0]
    _execute(url, "INSERT INTO trading.pm_token_versions (token_id, version_no, outcome_index, observed_at, received_at) VALUES (:t, 1, 0, now(), now()), (:t1, 1, 1, now(), now())", {"t": t0, "t1": t1})
    tv0 = _query(url, "SELECT id FROM trading.pm_token_versions WHERE token_id=:t", {"t": t0})[0][0]
    tv1 = _query(url, "SELECT id FROM trading.pm_token_versions WHERE token_id=:t", {"t": t1})[0][0]
    sha = "c" * 64
    _execute(url, "INSERT INTO trading.artifact_objects (sha256, original_size, stored_size, mime, compression, storage_driver, storage_version, locator) VALUES (:sha, 10, 10, 'application/json', 'none', 'local', 'cas/v1', :loc)", {"sha": sha, "loc": f"cas/v1/sha256/{sha[:2]}/{sha[2:4]}/{sha}.raw"})
    art = _query(url, "SELECT id FROM trading.artifact_objects WHERE sha256=:sha", {"sha": sha})[0][0]
    _execute(url, "INSERT INTO trading.contract_snapshots (market_version_id, yes_token_version_id, no_token_version_id, artifact_object_id, rules, resolution_source, clarification, content_hash) VALUES (:mv, :tv0, :tv1, :art, 'r', 'g', 'c', :h)", {"mv": mv, "tv0": tv0, "tv1": tv1, "art": art, "h": "b" * 64})
    snap = _query(url, "SELECT id FROM trading.contract_snapshots ORDER BY id DESC LIMIT 1")[0][0]
    spec = _query(
        url,
        "SELECT nextval(pg_get_serial_sequence('trading.contract_specs', 'id'))",
    )[0][0]
    spec_insert = (
        "INSERT INTO trading.contract_specs "
        "(id, contract_key, version_no, snapshot_id, kc_resolution_states, token_ids, "
        " token_count, state_count, compiler_version, schema_version, status, content_hash) "
        "VALUES (:id, 'c1', 1, :snap, CAST(:states AS jsonb), CAST(:toks AS jsonb), "
        "2, 2, 'lookup/v1', 1, :status, :h)",
        {
            "id": spec,
            "snap": snap,
            "states": json.dumps(["YES", "NO"]),
            "toks": json.dumps({"0": str(t0), "1": str(t1)}),
            "status": "pass",
            "h": "d" * 64,
        },
    )
    return {
        "mid": mid, "t0": t0, "t1": t1, "tv0": tv0, "tv1": tv1,
        "snap": snap, "spec": spec, "spec_insert": spec_insert,
    }


def _payout_stmt(spec, tok, token_version, outcome_index, function_ir):
    return (
        "INSERT INTO trading.payout_functions "
        "(contract_spec_id, pm_token_id, token_version_id, outcome_index, function_ir, "
        " test_vectors, algorithm_hash, content_hash) "
        "VALUES (:s, :t, :tv, :oi, CAST(:ir AS jsonb), '{}'::jsonb, :ah, :ch)",
        {
            "s": spec,
            "t": tok,
            "tv": token_version,
            "oi": outcome_index,
            "ir": json.dumps(function_ir),
            "ah": "e" * 64,
            "ch": ("f" if outcome_index == 0 else "9") * 64,
        },
    )


def test_payout_completeness_deferred_trigger(temp_pg_db):
    """deferred trigger：同事务插入完整 |K_c| 个 payout 才通过。"""
    url = temp_pg_db.url
    _run(command.upgrade, "head", url)
    env = _seed_payout_env(url)

    # 完整：同一事务 2 个 payout → commit 通过
    _exec_multi(url, [
        env["spec_insert"],
        _payout_stmt(env["spec"], env["t0"], env["tv0"], 0, {"YES": "1", "NO": "0"}),
        _payout_stmt(env["spec"], env["t1"], env["tv1"], 1, {"YES": "0", "NO": "1"}),
    ])
    assert _query(url, "SELECT count(*) FROM trading.payout_functions WHERE contract_spec_id=:s", {"s": env["spec"]})[0][0] == 2


