def _run(cmd, revision, db_url):
    cfg = Config()
    cfg.set_main_option("script_location", str(ALEMBIC_DIR))
    engine = create_engine(db_url, poolclass=NullPool)
    conn = engine.connect()
    cfg.attributes["connection"] = conn
    try:
        cmd(cfg, revision)
    finally:
        conn.close()
        engine.dispose()


def _query(db_url, sql, params=None):
    engine = create_engine(db_url)
    try:
        with engine.connect() as c:
            return c.execute(text(sql), params or {}).fetchall()
    finally:
        engine.dispose()


def _execute(db_url, sql, params=None):
    engine = create_engine(db_url)
    try:
        with engine.connect() as c:
            c.execute(text(sql), params or {})
            c.commit()
    finally:
        engine.dispose()


def _exec_multi(db_url, statements):
    """同事务执行多条语句后一次 commit（deferred trigger 需同事务）。"""
    engine = create_engine(db_url)
    try:
        with engine.connect() as c:
            for stmt in statements:
                c.execute(text(stmt[0]), stmt[1])
            c.commit()
    finally:
        engine.dispose()


def _version(db_url):
    return _query(db_url, "SELECT version_num FROM public.alembic_version")


def _trading_tables(db_url):
    return [r[0] for r in _query(
        db_url, "SELECT tablename FROM pg_tables WHERE schemaname='trading' ORDER BY 1"
    )]


def test_literal_empty_roundtrip(temp_pg_db):
    url = temp_pg_db.url
    _run(command.upgrade, V12, url)
    assert _version(url) == [(V12,)]
    assert set(SEMANTICS_TABLES) <= set(_trading_tables(url))

    _run(command.downgrade, V11, url)
    assert _version(url) == [(V11,)]
    assert set(SEMANTICS_TABLES).isdisjoint(set(_trading_tables(url)))

    _run(command.upgrade, V12, url)
    assert _version(url) == [(V12,)]


def test_existing_base_upgrade_preserves_base(temp_pg_db):
    url = temp_pg_db.url
    # apply Base fixture at baseline
    u = make_url(url)
    import subprocess, os
    cmd = ["psql", "-q", "-v", "ON_ERROR_STOP=1"]
    if u.host:
        cmd += ["-h", u.host]
    if u.port:
        cmd += ["-p", str(u.port)]
    if u.username:
        cmd += ["-U", u.username]
    cmd += ["-d", u.database, "-f", str(FIXTURE_SQL)]
    r = subprocess.run(cmd, capture_output=True, text=True)
    assert r.returncode == 0, r.stderr[-2000:]

    _run(command.upgrade, V12, url)
    assert _version(url) == [(V12,)]
    # Base 18 表保留（含 alembic_version 共 19）
    public_tables = [r[0] for r in _query(
        url, "SELECT tablename FROM pg_tables WHERE schemaname='public' ORDER BY 1"
    )]
    assert len(public_tables) == 19
    assert "alembic_version" in public_tables


